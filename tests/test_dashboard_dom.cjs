/* DOM-only interaction checks. Requires jsdom for tests, not for report users. */
const fs = require('node:fs');
const assert = require('node:assert/strict');
const {JSDOM, VirtualConsole} = require(process.env.TORTUGA_JSDOM || 'jsdom');
const errors = [];
const consoleCapture = new VirtualConsole();
consoleCapture.on('jsdomError', error => errors.push(error.message));
const dom = new JSDOM(fs.readFileSync(process.argv[2], 'utf8'), {
  runScripts: 'dangerously', url: 'https://offline-report.invalid/', virtualConsole: consoleCapture,
  beforeParse(window) {
    window.HTMLDialogElement.prototype.showModal = function() {this.open = true;};
    window.HTMLDialogElement.prototype.close = function() {this.open = false;};
    window.fetch = () => {throw new Error('An offline report must not fetch resources');};
    window.XMLHttpRequest = class {constructor() {throw new Error('An offline report must not request resources');}};
  }
});
const document = dom.window.document;
const reportData = JSON.parse(document.getElementById('report-data').textContent);
assert.equal(reportData.samples[0].mito.annotation.warnings.length, 1);
const click = selector => {const node = document.querySelector(selector); assert(node, 'Missing control '+selector); node.dispatchEvent(new dom.window.MouseEvent('click', {bubbles:true}));};
const text = () => document.querySelector('#view').textContent;
const noCommentary = () => {
  assert(!text().includes('Some feature coordinates'));
  assert(!text().includes('those features were omitted'));
  assert(!text().includes('The annotation stage did not complete'));
  assert(!text().includes('Exploratory MITOS'));
  assert(!text().includes('BOLD near-best score window'));
  assert.equal(document.querySelectorAll('#view .note.warning').length, 0);
};
assert.equal(document.querySelector('#sample-name').textContent, 'W30877');
assert.equal(document.querySelectorAll('.sample-row').length, 8);
assert(text().includes('15,740'));
assert(document.querySelectorAll('.gene').length > 10);
assert(!text().includes('Circular assembly, shown unrolled'));
assert(!text().includes('Exploratory MITOS annotation of the retained candidate.'));
assert(document.querySelector('.evidence').textContent.includes('COI reference match'));
assert(text().includes('13 / 13'));
assert(text().includes('High'));
assert(document.querySelector('#expected-hierarchy').textContent.includes('Animalia'));
assert(!document.querySelector('.evidence').textContent.includes('unresolved'));
noCommentary();
click('.gene');
assert(document.querySelector('.feature-readout').textContent.includes('cox1'));
assert(document.querySelector('.sequence-popover textarea').value.length > 1000);
const geneSequence = document.querySelector('.sequence-popover textarea').value;
click('.copy-sequence');
assert.equal(document.querySelector('.sequence-popover textarea').value, geneSequence);
assert(document.querySelector('.sequence-popover a[download]').getAttribute('href').startsWith('data:text/plain'));
click('[aria-label="Close sequence"]');
click('.view-switch button:last-child');
noCommentary();
assert.equal(document.querySelectorAll('.graph .segment').length, 3);
assert(text().includes('Source graphs · 1'));
assert(text().includes('Result files ·'));
assert(!text().includes('All retained files'));
click('.graph .segment');
assert(document.querySelector('.graph-readout').textContent.includes('Segment 1'));
assert(document.querySelector('.sequence-popover').textContent.includes('Assembly COI match'));
assert(document.querySelector('.sequence-popover textarea').value.length > 4000);
click('[aria-label="Close sequence"]');
click('[aria-label="Zoom in"]'); click('[aria-label="Zoom out"]'); click('[aria-label="Fit graph"]');
click('[data-branch="its"]');
noCommentary();
assert(text().includes('990'));
assert(!text().includes('Flanking rRNA anchors'));
assert(!text().includes('Resolution:'));
assert.equal(document.querySelectorAll('.gene').length, 5);
const select = document.querySelector('[aria-label="Reported ITS locus"]');
select.value = '1'; select.dispatchEvent(new dom.window.Event('change'));
assert(text().includes('1,040'));
click('.view-switch button:last-child');
assert.equal(document.querySelectorAll('.graph .segment').length, 5);
assert.equal(document.querySelectorAll('.graph .path-node').length, 3);
assert.equal(document.querySelectorAll('.graph .shared-node').length, 1);
assert(document.querySelector('.path-equation').textContent.includes('7,280 bp'));
assert(document.querySelector('.path-equation').textContent.includes('100 overlap bp'));
click('[data-branch="run"]');
noCommentary();
assert(text().includes('timeout'));
assert(!text().includes('A successful tool invocation'));
const timeoutLog = document.querySelector('a.stage-status.timeout');
assert(timeoutLog);
assert.equal(timeoutLog.getAttribute('href'), 'W30877/logs/wgs.log');
assert.equal(timeoutLog.getAttribute('download'), 'wgs.log');
assert.equal(document.querySelector('a.stage-status.failed').getAttribute('href'), 'W30877/logs/mtgrasp.log');
click('#compare'); assert(document.querySelector('#comparison').open);
click('#close-comparison'); assert(!document.querySelector('#comparison').open);
const input = document.querySelector('#search');
input.value = 'Geodia'; input.dispatchEvent(new dom.window.Event('input'));
assert.equal(document.querySelectorAll('.sample-row').length, 1);
click('.sample-row'); click('[data-branch="its"]');
assert(text().includes('No complete ITS locus reported'));
assert(document.querySelector('#sample-status').textContent.includes('ITSME · completed'));
assert(!document.querySelector('#sample-status').classList.contains('fail'));
click('[data-branch="mito"]');
assert(text().includes('No annotation map available'));
assert(document.querySelector('.evidence').textContent.includes('COI reference match'));
assert(document.querySelector('.evidence').textContent.includes('Geodia'));
assert(!document.querySelector('.evidence').textContent.includes('unresolved'));
const evidence = [...document.querySelectorAll('details')].find(node => node.querySelector('summary').textContent === 'Taxonomic evidence');
assert(evidence && !evidence.open);
assert(evidence.textContent.includes('Unconfirmed'));
evidence.open = true;
noCommentary();
click('[data-branch="run"]');
assert(document.querySelector('span.stage-status.failed'));
assert(!document.querySelector('a.stage-status.failed'));
assert(!text().includes('null'));
// A historical confirmation flag cannot fill an observed-taxonomy field.
dom.window.eval("state.sample=0; state.branch='mito'; report.samples[0].mito.hits=[]; report.samples[0].mito.reference_taxa=[]; report.samples[0].mito.confidence={grade:'Unavailable',taxon:''}; render();");
assert(document.querySelector('.evidence').textContent.includes('No COI match'));
assert(!document.querySelector('.evidence').textContent.includes('Rathbunixa occidentalis'));
assert.equal(document.querySelectorAll('[src^="http"],link[href^="http"]').length, 0);
// A retained native graph stays downloadable when no final path was mapped.
dom.window.eval("report.samples[0].mito.graphs=[]; state.mode='graph'; render();");
assert(text().includes('Selected path unavailable'));
assert(!text().includes('Source graph unavailable'));
const sourceLink = [...document.querySelectorAll('a')].find(node => node.getAttribute('href') === reportData.samples[0].mito.source_graphs[0].href);
assert(sourceLink && sourceLink.hasAttribute('download'));
dom.window.eval("report.samples[0].mito.source_graphs=[]; render();");
assert(text().includes('Source graph unavailable'));
assert(!text().includes('Selected path unavailable'));
// Split RNA segments occupy their annotated bases, not the parent envelope.
dom.window.eval("state.mode='map'; report.samples[0].mito.length=18949; report.samples[0].mito.annotation.features.push({gene:'rrnL_0',type:'rRNA',start:17751,end:879,segments:[[17751,18475],[1,879]],strand:'+',sequence:'A'.repeat(1604)}); render();");
const splitRna = document.querySelector('g[aria-label^="rrnL_0,"]');
assert(splitRna && splitRna.querySelectorAll('rect').length === 2);
assert([...splitRna.querySelectorAll('rect')].reduce((sum, rect) => sum+Number(rect.getAttribute('width')), 0) < 80);
splitRna.dispatchEvent(new dom.window.MouseEvent('click', {bubbles:true}));
assert(document.querySelector('.feature-readout').textContent.includes('17,751–18,475; 1–879'));
assert.equal(document.querySelector('.sequence-popover textarea').value.length, 1604);
assert.deepEqual(errors, []);
console.log('Passed offline DOM checks: filtering, sample/branch/locus switching, gene selection, GFA/FASTG selection, zoom buttons, comparison, run failures and missing results.');
dom.window.close();
